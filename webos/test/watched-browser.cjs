const assert = require('node:assert/strict');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
  try {
    const page = await browser.newPage({viewport:{width:1920,height:1080}}), errors=[], calls=[];
    page.on('pageerror', e=>errors.push(e.message));
    const movie={Id:'movie',Name:'Resume movie',Type:'Movie',MediaType:'Video',RunTimeTicks:18000000000,UserData:{Played:true,PlaybackPositionTicks:600000000,PlayedPercentage:30,IsFavorite:true}};
    const episode={Id:'episode',Name:'Resume episode',SeriesId:'show',SeriesName:'Test show',ParentIndexNumber:1,IndexNumber:1,Type:'Episode',MediaType:'Video',RunTimeTicks:18000000000,UserData:{Played:true,PlaybackPositionTicks:450000000,PlayedPercentage:25}};
    const show={Id:'show',Name:'Test show',Type:'Series',IsFolder:true};
    const next={...episode,Id:'next',Name:'Unrelated next episode',SeriesId:'other',UserData:{Played:false}};
    let failMutation=false;
    await page.route('https://jellyfin.test/**', async route=>{
      const req=route.request(), u=new URL(req.url());
      calls.push({path:u.pathname,method:req.method()});
      let data={Items:[]};
      if(u.pathname.endsWith('/Views')) data={Items:[{Id:'movies',Name:'Movies',CollectionType:'movies'},{Id:'tv',Name:'TV',CollectionType:'tvshows'}]};
      else if(u.pathname.includes('/PlayedItems/')) {
        if(failMutation) return route.fulfill({status:500,json:{}});
        const item=u.pathname.endsWith('/movie') ? movie : episode;
        item.UserData={...item.UserData,Played:req.method()==='POST',PlaybackPositionTicks:0,PlayedPercentage:0,PlayCount:0,LastPlayedDate:null};
        data=item.UserData;
      } else if(u.pathname.endsWith('/Resume')) data={Items:[movie,episode].filter(item=>item.UserData.PlaybackPositionTicks>0)};
      else if(u.pathname==='/Shows/NextUp') data={Items:[next]};
      else if(u.pathname.endsWith('/Latest')) data=u.searchParams.get('ParentId')==='tv' ? [show] : [movie];
      else if(u.pathname.endsWith('/Seasons')) data={Items:[{Id:'season',Name:'Season 1',IndexNumber:1,Type:'Season',IsFolder:true}]};
      else if(u.pathname.endsWith('/Episodes') || (u.pathname==='/Users/user/Items' && u.searchParams.get('ParentId')==='season')) data={Items:[episode],TotalRecordCount:1};
      else if(u.pathname.startsWith('/Users/user/Items/')) data=[movie,episode,show].find(item=>u.pathname.endsWith('/'+item.Id))||{};
      else if(u.pathname.endsWith('/PlaybackInfo')) data={MediaSources:[{Id:'source',MediaStreams:[]}]};
      return route.fulfill({json:data});
    });
    await page.addInitScript(()=>localStorage.setItem('wholphin-session',JSON.stringify({server:'https://jellyfin.test',user:'user',token:'mock'})));
    await page.goto(pathToFileURL(path.join(process.env.APP_DIR || path.resolve(__dirname,'../app'),'index.html')).href);
    const resumed = id=>page.locator('#home-rows [data-row="continue"] [data-item="'+id+'"]');
    await resumed('movie').waitFor();
    await resumed('episode').waitFor();
    await resumed('movie').click();
    const unwatched=()=>page.getByRole('button',{name:'Mark as unwatched',exact:true});
    await page.getByRole('button',{name:'Resume',exact:true}).waitFor();
    failMutation=true;
    await unwatched().click();
    await page.getByText('Jellyfin request failed (500).',{exact:true}).waitFor();
    assert.equal(movie.UserData.PlaybackPositionTicks,600000000,'A failed request must preserve progress');
    assert.equal(await unwatched().isVisible(),true);
    assert.equal(await page.getByRole('button',{name:'Resume',exact:true}).isVisible(),true);
    failMutation=false;
    await unwatched().click();
    await page.getByRole('button',{name:'Mark as watched',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Resume',exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Remove from favorites',exact:true}).isVisible(),true);
    const before=calls.filter(c=>c.path.endsWith('/Resume')).length;
    await page.locator('nav [data-nav=home]').click();
    await resumed('episode').waitFor();
    assert.equal(await resumed('movie').count(),0,'Unwatched movies must leave the cached Continue Watching row');
    assert(calls.filter(c=>c.path.endsWith('/Resume')).length>before,'Home must refetch resume data immediately');
    await page.locator('[data-row="latest:tv"]').scrollIntoViewIfNeeded();
    await page.locator('[data-row="latest:tv"] [data-item=show]').click();
    await page.locator('.episode-browser-rail [data-item=episode]').waitFor();
    assert.equal(await page.locator('.episode-browser-actions button').first().getAttribute('aria-label'),'Resume');
    await unwatched().click();
    await page.getByRole('button',{name:'Mark as watched',exact:true}).waitFor();
    assert.equal(await page.locator('.episode-browser-actions button').first().getAttribute('aria-label'),'Play');
    await page.locator('nav [data-nav=home]').click();
    await resumed('next').waitFor();
    assert.equal(await resumed('episode').count(),0,'Unwatched episodes must leave Continue Watching');
    assert.equal(await resumed('movie').count(),0);
    assert(calls.some(c=>c.method==='DELETE' && c.path==='/Users/user/PlayedItems/episode'));
    assert.deepEqual(errors,[]);
    console.log('PASS: unwatched movies/season episodes clear resume data, invalidate Home, preserve favorites and handle failures');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
